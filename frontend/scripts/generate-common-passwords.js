// Writes lib/commonPasswords.js from the backend's bundled list (backend/data/common-passwords.txt).
// Only entries of 12 or more characters are kept: anything shorter already fails the length rule, and this keeps
// the browser download small. Run with: node frontend/scripts/generate-common-passwords.js
const fs = require("fs");
const path = require("path");

const MIN_LENGTH = 12;
const comparable = (value) => value.normalize("NFKC").toLowerCase();

function longCommonPasswords(text) {
  const entries = text.split(/\r?\n/).filter(Boolean).filter((entry) => Array.from(entry.normalize("NFKC")).length >= MIN_LENGTH).map(comparable);
  return [...new Set(entries)].sort();
}

if (require.main === module) {
  const source = fs.readFileSync(path.join(__dirname, "../../backend/data/common-passwords.txt"), "utf8");
  const list = longCommonPasswords(source);
  const output = "// Generated by scripts/generate-common-passwords.js from backend/data/common-passwords.txt. Do not edit.\n"
    + "// The common passwords that are long enough to pass the length rule, lower-cased after NFKC normalization.\n"
    + "export const LONG_COMMON_PASSWORDS = " + JSON.stringify(list, null, 0).replace(/","/g, "\",\n\"") + ";\n";
  fs.writeFileSync(path.join(__dirname, "../lib/commonPasswords.js"), output);
  console.log(`Wrote ${list.length} passwords.`);
}

module.exports = { longCommonPasswords };
